"""
Arabic (ar) translations for the driver certification course — S7.

Scope note (2026-09-26): this module is intentionally additive and
stand-alone. A parallel pass is translating the same course into Amharic by
adding `am=`/`lead_am=` keyword args directly on the `_tri()`/`_block()`
calls inside `COURSE_MODULES`/`QUIZ_QUESTIONS` in certification.py. To avoid
two agents editing the same ~180 call sites at once, the Arabic pass instead
overlays translated text onto the JSON-safe dict that
`certification.course_content_public()` already builds, keyed by module
`key` (m1..m13) and by list position for quiz questions/options. It never
touches COURSE_MODULES, QUIZ_QUESTIONS, `_tri()`, `_block()`, or `_opt()`,
never reorders modules/questions/options, and never changes a quiz
`correct` index — it only replaces the `"ar"` value inside otherwise
untouched dicts. `course_content_public()` calls `apply_ar_translations()`
as the last, single-line step before returning; that is the only edit this
pass makes to certification.py.

Sourcing: docs/training/glossary-ar.md (18 domain terms, 2+ sources each).
Reviewer guide / least-sure lines: docs/training/translation-notes-ar.md.

Register: Modern Standard Arabic (MSA), fifth-grade reading level, aimed at
Sudanese, Somali-Arabic, Iraqi, and Syrian drivers in Seattle — no
dialect-specific slang. Numbers, clock times, dates, and dollar amounts use
Western digits throughout (matches the app and the existing 'ar' UI chrome
in frontend/app/(public)/training/[token]/page.tsx).

Bidi handling: the course text never names internal software (see
certification.py's module docstring) but it does use partner/company names,
the two in-app button labels, and a couple of external form/process names.
Those Latin tokens are wrapped in Unicode directional isolates (U+2066 /
U+2069) so they render correctly embedded inside right-to-left Arabic
sentences, regardless of which RTL engine renders the page. Plain digits
(times, dates, dollar figures, quiz numbers) are left un-isolated, matching
the pattern already shipped in the frontend chrome translations.
"""
from __future__ import annotations

# ---------------------------------------------------------------------------
# Bidi isolation for embedded Latin tokens
# ---------------------------------------------------------------------------

_LRI = "⁦"  # left-to-right isolate
_PDI = "⁩"  # pop directional isolate


def _iso(latin: str) -> str:
    """Wrap a Latin-script token so it renders correctly embedded in an
    Arabic (RTL) sentence."""
    return f"{_LRI}{latin}{_PDI}"


