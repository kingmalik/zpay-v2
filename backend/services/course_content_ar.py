# ---------------------------------------------------------------------------
# Overlay — pure function, returns a new dict, mutates nothing it is given.
# ---------------------------------------------------------------------------

def _block_with_ar(block: dict, lead_ar: str | None, text_ar: str) -> dict:
    lead = block["lead"]
    if lead is not None and lead_ar is not None:
        lead = {**lead, "ar": lead_ar}
    text = {**block["text"], "ar": text_ar}
    return {"lead": lead, "text": text}


def _module_with_ar(m: dict, dispatch_phone: str) -> dict:
    key = m["key"]
    title = m["title"]
    if key in MODULE_TITLES:
        title = {**title, "ar": MODULE_TITLES[key]}

    intro = m["intro"]
    if intro is not None and key in MODULE_INTROS:
        intro = {**intro, "ar": MODULE_INTROS[key]}

    blocks_ar = _m1_blocks(dispatch_phone) if key == "m1" else MODULE_BLOCKS.get(key, [])
    blocks = (
        [_block_with_ar(b, lead_ar, text_ar) for b, (lead_ar, text_ar) in zip(m["blocks"], blocks_ar)]
        if blocks_ar
        else m["blocks"]
    )
    return {"key": key, "title": title, "intro": intro, "blocks": blocks}


def _question_with_ar(q: dict, question_ar: str, options_ar: list[str]) -> dict:
    question = {**q["question"], "ar": question_ar}
    options = [{**opt, "ar": opt_ar} for opt, opt_ar in zip(q["options"], options_ar)]
    return {"question": question, "options": options, "correct": q["correct"]}


def apply_ar_translations(content: dict, dispatch_phone: str) -> dict:
    """Return a NEW course-content dict (does not mutate `content`) with
    Arabic text overlaid module-by-module and question-by-question onto the
    English-sourced JSON from certification.course_content_public(). Leaves
    'en'/'am' untouched, never reorders modules/questions/options, and never
    changes a quiz `correct` index."""
    return {
        **content,
        "modules": [_module_with_ar(m, dispatch_phone) for m in content["modules"]],
        "quiz": [
            _question_with_ar(q, question_ar, options_ar)
            for q, (question_ar, options_ar) in zip(content["quiz"], QUIZ)
        ],
    }
